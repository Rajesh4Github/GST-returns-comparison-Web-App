def extract_arn_date_from_pdf(pdf_path):
    try:
        with pdfplumber.open(pdf_path) as pdf:
            for page in pdf.pages:
                text = page.extract_text()
                if text:
                    # Search for ARN date patterns, e.g., 'ARN Date', 'ARN : ... Date', or patterns near 'ARN'
                    # Common pattern: ARN Date : DD/MM/YYYY or ARN: AA1234567890123 Date: DD/MM/YYYY
                    match_arn = re.search(r"ARN\s*.*?Date\s*[:\-]?\s*(\d{2}/\d{2}/\d{4})", text, re.IGNORECASE)
                    if match_arn:
                        return match_arn.group(1).strip()

                    # Alternative: Look for Application Reference Number and any date on the same line or next line
                    match_ref = re.search(r"Application\s*Reference\s*Number.*?(\d{2}/\d{2}/\d{4})", text, re.IGNORECASE | re.DOTALL)
                    if match_ref:
                        return match_ref.group(1).strip()

                    # Alternative: standard date in verification section as a fallback if ARN keywords are generic
                    if "verification" in text.lower() or "signature" in text.lower():
                        dates = re.findall(r"\b\d{2}/\d{2}/\d{4}\b", text)
                        if dates:
                            return dates[-1]
    except Exception as e:
        print(f"Error parsing {pdf_path}: {e}")
    return None

