def parse_and_populate_gstr1_pdf(pdf_path, df):
    try:
        reader = PdfReader(pdf_path)
        full_text = "\n".join([page.extract_text() for page in reader.pages if page.extract_text()])
    except Exception as e:
        print(f"Error reading {pdf_path}: {e}")
        return

    col = get_month_key(os.path.basename(pdf_path), full_text)
    if col == "UNKNOWN":
        print(f"Could not determine month for {pdf_path}")
        return

    # Extract Table 4A (B2B Regular)
    b2b = re.search(r"4A.*?Total\s+(\d+)\s+Invoice\s+([\d,]+\.\d+)\s+([\d,]+\.\d+)\s+([\d,]+\.\d+)\s+([\d,]+\.\d+)\s+([\d,]+\.\d+)", full_text, re.DOTALL)
    if b2b:
        vals = [clean_value(b2b.group(i)) for i in range(2, 7)] # Taxable Value, IGST, CGST, SGST, Cess
        fields = ["Taxable Value", "IGST", "CGST", "SGST", "Cess"]
        for f, val in zip(fields, vals):
            df.loc[(df["Table Section"] == "4A - B2B Regular") & (df["Details / Field"] == f), col] = val

    # Extract Table 7 (B2CS)
    b2cs = re.search(r"7\s*-\s*Taxable supplies.*?Total\s+(\d+)\s+Net Value\s+([\d,]+\.\d+)\s+([\d,]+\.\d+)\s+([\d,]+\.\d+)\s+([\d,]+\.\d+)\s+([\d,]+\.\d+)", full_text, re.DOTALL)
    if b2cs:
        vals = [clean_value(b2cs.group(i)) for i in range(2, 7)] # Net Value, IGST, CGST, SGST, Cess
        fields = ["Net Value", "IGST", "CGST", "SGST", "Cess"]
        for f, val in zip(fields, vals):
            df.loc[(df["Table Section"] == "7 - B2CS (Others)") & (df["Details / Field"] == f), col] = val

    # Extract Table 8 (Nil rated, exempted)
    nil_val = re.search(r"8\s*-\s*Nil rated.*?Total\s+([\d,]+\.\d+)", full_text, re.DOTALL)
    if nil_val:
        df.loc[(df["Table Section"] == "8 - Nil Rated, Exempted & Non-GST") & (df["Details / Field"] == "Nil Rated Value"), col] = clean_value(nil_val.group(1))

    # Total Liability
    tot_liab = re.search(r"Total Liability.*?([\d,]+\.\d+)\s+([\d,]+\.\d+)\s+([\d,]+\.\d+)\s+([\d,]+\.\d+)\s+([\d,]+\.\d+)", full_text, re.DOTALL)
    if tot_liab:
        vals = [clean_value(tot_liab.group(i)) for i in range(1, 6)] # Taxable Value, IGST, CGST, SGST, Cess
        fields = ["Taxable Value", "IGST", "CGST", "SGST", "Cess"]
        for f, val in zip(fields, vals):
            df.loc[(df["Table Section"] == "Total Liability (Outward supplies other than Reverse charge)") & (df["Details / Field"] == f), col] = val

