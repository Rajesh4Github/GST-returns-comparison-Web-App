# Helper to extract the actual filing date from GSTR-3B PDF
def extract_filing_date_from_pdf(pdf_path):
    try:
        with pdfplumber.open(pdf_path) as pdf:
            for page in pdf.pages:
                text = page.extract_text()
                if text:
                    # Search for standard filing date labels
                    match = re.search(r"Date of filing\s*:\s*([0-9/\\-]+)", text, re.IGNORECASE)
                    if match:
                        return match.group(1).strip()

                    # Alternative search for standard pattern DD/MM/YYYY near "Filing Date"
                    match_alt = re.search(r"Filing Date\s*([0-9/\\-]+)", text, re.IGNORECASE)
                    if match_alt:
                        return match_alt.group(1).strip()

                    # Generic date extraction under a verification block
                    if "verification" in text.lower():
                        dates = re.findall(r"\b\d{2}/\d{2}/\d{4}\b", text)
                        if dates:
                            return dates[-1] # Usually the verification/filing date is near the end
    except Exception as e:
        print(f"Error reading {pdf_path}: {e}")
    return None

