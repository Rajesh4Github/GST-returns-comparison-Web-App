def clean_value(val):
    """
    Cleans and converts extracted PDF cell values into floats.
    - Removes commas, spaces, newlines
    - Strips alphabetic artifacts
    - Converts to float if numeric, else returns 0.0
    """
    if val is None:
        return 0.0
    val_str = str(val).replace(",", "").replace(" ", "").replace("\n", "").strip()
    val_str = re.sub(r"^[a-zA-Z\s/]+(?!\d)", "", val_str)  # remove leading letters
    val_str = re.sub(r"^[a-zA-Z]+", "", val_str)
    if val_str in ["", "-", ".", "0.00"]:
        return 0.0
    match = re.search(r"[-+]?\d*\.\d+|[-+]?\d+", val_str)
    if match:
        try:
            return float(match.group())
        except ValueError:
            return 0.0
    return 0.0


def get_month_key(filename, pdf_text=""):
    """
    Determines the fiscal month (APR–MAR) from either:
    - The filename (e.g., GSTR1_APR2024.pdf)
    - The text inside the PDF
    - Regex pattern (_MMYYYY)
    Returns: Month abbreviation (APR, MAY, JUN, …) or 'UNKNOWN'
    """
    fname_lower = filename.lower()
    months_map = {
        'apr': 'APR', 'april': 'APR', '04': 'APR',
        'may': 'MAY', '05': 'MAY',
        'jun': 'JUN', 'june': 'JUN', '06': 'JUN',
        'jul': 'JUL', 'july': 'JUL', '07': 'JUL',
        'aug': 'AUG', 'august': 'AUG', '08': 'AUG',
        'sep': 'SEP', 'september': 'SEP', '09': 'SEP',
        'oct': 'OCT', 'october': 'OCT', '10': 'OCT',
        'nov': 'NOV', 'november': 'NOV', '11': 'NOV',
        'dec': 'DEC', 'december': 'DEC', '12': 'DEC',
        'jan': 'JAN', 'january': 'JAN', '01': 'JAN',
        'feb': 'FEB', 'february': 'FEB', '02': 'FEB',
        'mar': 'MAR', 'march': 'MAR', '03': 'MAR'
    }

    # Check filename
    for k, v in months_map.items():
        if k in fname_lower:
            return v

    # Check PDF text
    text_lower = pdf_text.lower()
    for k, v in months_map.items():
        if k in text_lower:
            return v

    # Regex fallback (_MMYYYY)
    match = re.search(r"_(\d{2})\d{4}", filename)
    if match:
        m_num = match.group(1)
        map_num = {"04": "APR", "05": "MAY", "06": "JUN", "07": "JUL",
                   "08": "AUG", "09": "SEP", "10": "OCT", "11": "NOV",
                   "12": "DEC", "01": "JAN", "02": "FEB", "03": "MAR"}
        return map_num.get(m_num, "UNKNOWN")

    return "UNKNOWN"

