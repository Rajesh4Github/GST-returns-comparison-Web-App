def compute_due_dates_and_interest(df):
    for m in MONTH_COLUMNS:
        due_date = DUE_DATES.get(m)
        if not due_date:
            continue

        due_date_str = due_date.strftime("%d/%m/%Y")
        df.loc[df["Details / Field"] == "3B Due Date", m] = due_date_str

        filing_date_val = df.loc[df["Details / Field"] == "3B Filing Date", m].values[0]

        days_late = 0
        try:
            if pd.notna(filing_date_val) and str(filing_date_val).strip() not in ["0.00", "0", "nan", ""]:
                f_date_str = str(filing_date_val).strip()
                f_date = pd.to_datetime(f_date_str, dayfirst=True)
                if pd.notna(f_date):
                    delta = (f_date - due_date).days
                    days_late = max(0, delta)
        except Exception:
            days_late = 0

        df.loc[df["Details / Field"] == "No. of days late", m] = float(days_late)

        # Extract Interest Paid in Cash from Section 6.1
        try:
            igst_int_paid = float(df.loc[(df["HEADING"].str.contains("Interest paid in Cash", case=False)) & (df["Details / Field"] == "IGST Interest"), m].values[0] or 0.0)
            cgst_int_paid = float(df.loc[(df["HEADING"].str.contains("Interest paid in Cash", case=False)) & (df["Details / Field"] == "CGST Interest"), m].values[0] or 0.0)
            sgst_int_paid = float(df.loc[(df["HEADING"].str.contains("Interest paid in Cash", case=False)) & (df["Details / Field"] == "SGST Interest"), m].values[0] or 0.0)
            cess_int_paid = float(df.loc[(df["HEADING"].str.contains("Interest paid in Cash", case=False)) & (df["Details / Field"] == "CESS Interest"), m].values[0] or 0.0)
        except Exception:
            igst_int_paid = cgst_int_paid = sgst_int_paid = cess_int_paid = 0.0

        # Interest Payable = 0.18 * Tax (Interest Paid in Cash) * (days_late / 365)
        igst_interest_payable = round(igst_int_paid * 0.18 * (days_late / 365.0), 2)
        cgst_interest_payable = round(cgst_int_paid * 0.18 * (days_late / 365.0), 2)
        sgst_interest_payable = round(sgst_int_paid * 0.18 * (days_late / 365.0), 2)
        cess_interest_payable = round(cess_int_paid * 0.18 * (days_late / 365.0), 2)

        df.loc[df["Details / Field"] == "IGST Interest Payable", m] = igst_interest_payable
        df.loc[df["Details / Field"] == "CGST Interest Payable", m] = cgst_interest_payable
        df.loc[df["Details / Field"] == "SGST Interest Payable", m] = sgst_interest_payable
        df.loc[df["Details / Field"] == "CESS Interest Payable", m] = cess_interest_payable

    return df

